import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { PHASE_TITLES, type Phase } from "../rules/phase.js";
import { ALL_RULES } from "../rules/registry.js";

const START = "<!-- deslopify:start (generated by `deslopify sync`; edit rules in .deslopify/config.json) -->";
const END = "<!-- deslopify:end -->";
const PHASES: Phase[] = ["before", "write", "finish"];

/** The agent's standing instructions, generated from the rule registry so text and checks cannot drift apart. */
export function renderInstructions(): string {
  const sections = PHASES.map((phase) => {
    const lines = ALL_RULES.filter((r) => r.phase === phase).map((r) => `- ${r.instruction} [${r.id}]`);
    return [`## ${PHASE_TITLES[phase]}`, ...lines].join("\n");
  });
  return [
    START,
    "# How to work in this repo",
    "",
    "Precedence: the user's request > .deslopify/direction.json > these rules > your defaults.",
    "Read .deslopify/codemap.md first: reuse what it marks ★, and put code in the layer it names.",
    "",
    ...sections.flatMap((s) => [s, ""]),
    "A hook names the rule ID when a check fails; fix the cause, never silence the check.",
    END,
  ].join("\n");
}

/** Write the managed block into AGENTS.md (replace in place, or append) and make CLAUDE.md import it. */
export function writeInstructions(root: string): void {
  const agents = join(root, "AGENTS.md");
  const block = renderInstructions();
  if (!existsSync(agents)) writeFileSync(agents, `${block}\n`);
  else {
    const text = readFileSync(agents, "utf8");
    const start = text.indexOf("<!-- deslopify:start");
    const end = text.indexOf(END);
    writeFileSync(agents, start >= 0 && end > start ? `${text.slice(0, start)}${block}${text.slice(end + END.length)}` : `${text.trimEnd()}\n\n${block}\n`);
  }

  const claude = join(root, "CLAUDE.md");
  const importLine = "@AGENTS.md";
  const current = existsSync(claude) ? readFileSync(claude, "utf8") : "";
  if (!current.split("\n").some((l) => l.trim() === importLine)) writeFileSync(claude, `${current.trimEnd()}${current ? "\n\n" : ""}${importLine}\n`);
}
