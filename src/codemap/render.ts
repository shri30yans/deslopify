import { posix } from "node:path";
import type { Config } from "../core/config.js";
import { FAMILY, jaccard, nameWords } from "./similarity.js";
import type { CodemapIndex, FileInfo, RankedSymbol } from "./types.js";

const tokens = (s: string): number => Math.ceil(s.length / 4);

function layersSection(config: Config): string[] {
  if (config.layers.length === 0) return [];
  return [
    "## Layers (imports flow down only)",
    config.layers.map((l) => `${l.name} (${l.paths.join(", ")})`).join(" → "),
    "",
  ];
}

const folderOf = (path: string): string => posix.dirname(path).split("/").slice(0, 3).join("/");

function foldersSection(index: CodemapIndex): string[] {
  const byDir = new Map<string, FileInfo[]>();
  for (const f of index.files) byDir.set(folderOf(f.path), [...(byDir.get(folderOf(f.path)) ?? []), f]);
  const rows = [...byDir.entries()]
    .map(([dir, files]) => {
      const top = index.symbols.filter((s) => folderOf(s.file) === dir && s.kind !== "type" && s.kind !== "interface").slice(0, 4).map((s) => s.name);
      return `- \`${dir}/\` ${files.length} file${files.length === 1 ? "" : "s"}${top.length ? `: ${top.join(", ")}` : ""}`;
    })
    .slice(0, 14);
  return ["## Folders", ...rows, ""];
}

function reuseRow(s: RankedSymbol): string {
  const star = s.canonical ? " ★" : "";
  return `| \`${s.name}\`${star} | ${s.kind} | ${s.file}:${s.line} | \`${s.signature.replace(/\|/g, "\\|")}\` | ${s.usedBy} |`;
}

/** Exported names in different files that look like the same job. */
export function duplicateClusters(symbols: readonly RankedSymbol[]): string[] {
  const out: string[] = [];
  const fns = symbols.filter((s) => s.kind !== "type" && s.kind !== "interface").slice(0, 300);
  for (let i = 0; i < fns.length; i++) {
    for (let j = i + 1; j < fns.length; j++) {
      const a = fns[i];
      const b = fns[j];
      if (a.file !== b.file && FAMILY[a.kind] === FAMILY[b.kind] && jaccard(nameWords(a.name), nameWords(b.name)) >= 0.8) out.push(`${a.name} (${a.file}) ≈ ${b.name} (${b.file})`);
    }
  }
  return out.slice(0, 6);
}

function watchSection(index: CodemapIndex, config: Config): string[] {
  const big = index.files
    .filter((f) => f.lines > config.budgets.fileLines && f.lang !== "css" && f.lang !== "md")
    .sort((a, b) => b.lines - a.lines)
    .slice(0, 6)
    .map((f) => `- ${f.path} ${f.lines} lines (budget ${config.budgets.fileLines}): split before adding`);
  const dups = duplicateClusters(index.symbols).map((d) => `- possible duplicate: ${d}`);
  const glossary = Object.entries(config.glossary).map(([term, avoid]) => `- say "${term}", not ${avoid.map((a) => `"${a}"`).join(", ")}`);
  const rows = [...big, ...dups, ...glossary];
  return rows.length ? ["## Watch", ...rows, ""] : [];
}

/**
 * The codemap the agent reads: atlas (layers, folders, do-not-edit) plus a reuse
 * index filled greedily by rank until the token budget is spent.
 */
export function renderCodemap(index: CodemapIndex, config: Config, symbols: readonly RankedSymbol[] = index.symbols): string {
  const head = [
    "# Codemap (generated by deslopify; do not edit)",
    "",
    "Reuse anything marked ★ before writing something new. Put code in the layer it belongs to.",
    "",
    ...layersSection(config),
    "## Do not edit",
    config.doNotEdit.join(" · "),
    "",
    ...foldersSection(index),
  ];
  const tail = watchSection(index, config);
  const tableHead = ["## Reuse first", "| Symbol | Kind | Where | Signature | Used by |", "|---|---|---|---|---|"];
  let budget = config.codemap.tokenBudget - tokens([...head, ...tail, ...tableHead].join("\n"));
  const rows: string[] = [];
  for (const s of symbols) {
    const row = reuseRow(s);
    if (budget - tokens(row) < 0) break;
    budget -= tokens(row);
    rows.push(row);
  }
  return [...head, ...tableHead, ...rows, "", ...tail].join("\n");
}
